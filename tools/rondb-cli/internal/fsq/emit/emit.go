type filterLeaf struct {
	feature   *feature
	condition spec.SqlCondition
	value     string
}

func (b *builder) createServingPreparedStatementDTOS(joins []spec.Join, filterConditions []spec.Filter, filtersNil bool) ([]Statement, error) {
	var out []Statement
	for _, join := range joins {
		fg := b.fgs[join.FG]
		if !fg.OnlineEnabled() {
			return nil, notOnlineEnabled(fg)
		}
		fgf := b.featuresOf(fg, join.Prefix)
		pks := primaryKeys(fgf)
		if len(pks) == 0 {
			return nil, primaryKeyRequired()
		}
		selectFeatures := getSelectFeatures(b.opt.Batch, b.opt.InferenceHelpers, join, fg, fgf, pks,
			b.opt.Logging, b.opt.VectorWithHelpers)
		if join.Aggregate != nil {
			selectFeatures = aggregateSourceFeatures(join.Aggregate, fgf, pks)
		}
		if join.CollectN != nil {
			selectFeatures = collectSourceFeatures(join, fg, fgf, pks)
		}
		if len(selectFeatures) == 0 {
			continue
		}
		q := &query{project: fg.OnlineDatabase(), fg: fg, features: selectFeatures}
		var collectOrderBy *feature
		if join.CollectN != nil && join.OrderBy != nil {
			collectOrderBy = fgf.get(*join.OrderBy)
		}
		excludedKey := ""
		if collectOrderBy != nil {
			excludedKey = *join.OrderBy
		} else if join.Aggregate != nil {
			excludedKey = fg.EventTime
		}
		var bindKeys []*feature
		for _, pk := range pks {
			if excludedKey == "" || pk.Name != excludedKey {
				bindKeys = append(bindKeys, pk)
			}
		}
		var extraFilters []filterLeaf
		var ronsqlExtraWhere strings.Builder
		var scanFilters []CollectFilter
		scanFilterable := true
		if join.CollectN != nil || join.Aggregate != nil {
			if filtersNil {
				return nil, spec.Gate(spec.CodeCollectUnsupportedOnlineFilt,
					"the feature view's filters contain OR, which cannot be applied to the online collect/aggregation statement for feature group %s", fg.Name)
			}
			for _, cond := range filterConditions {
				if _, ok := b.fgs[cond.FG]; !ok || cond.FG != fg.ID {
					continue
				}
				// review X7: a condition pinned to a join index applies to that join only
				if cond.JoinIndex != nil && *cond.JoinIndex != join.Index {
					continue
				}
				rendered, ok := renderRonsqlCondition(cond, fgf)
				if !ok {
					return nil, spec.Gate(spec.CodeCollectUnsupportedOnlineFilt,
						"the feature view's filter on '%s' cannot be applied to the online collect/aggregation statement for feature group %s", cond.Feature, fg.Name)
				}
				extraFilters = append(extraFilters, filterLeaf{feature: fgf.get(cond.Feature), condition: *cond.Condition, value: *cond.Value})
				ronsqlExtraWhere.WriteString(" AND " + rendered)
				if scanFilterConditions[*cond.Condition] {
					scanFilters = append(scanFilters, CollectFilter{Feature: cond.Feature, Condition: string(*cond.Condition),
						Value: *cond.Value, Type: fgf.get(cond.Feature).Type})
				} else {
					scanFilterable = false
				}
			}
		}
		dto, err := b.buildDTO(q, bindKeys, fg.ID, join.Index, b.opt.Batch, join.Prefix, join.CollectN, collectOrderBy,
			join.Ascending, extraFilters, ronsqlExtraWhere.String())
		if err != nil {
			return nil, err
		}
		if join.CollectN != nil && scanFilterable && len(scanFilters) > 0 {
			dto.CollectFilters = scanFilters
		}
		if err := applyRonsqlAggregate(&dto, join, fg, q, bindKeys, b.opt.Batch, ronsqlExtraWhere.String()); err != nil {
			return nil, err
		}
		applyMysqlAggregate(&dto, join, fg, q, bindKeys, b.opt.Batch, ronsqlExtraWhere.String())
		out = append(out, dto)
	}
	return out, nil
}

// getSelectFeatures :1249-1293.  Entries may be nil (a selected name that is
// not a feature-group column, e.g. an aggregate output), exactly like the
// Java list.
func getSelectFeatures(batch, inferenceHelperColumns bool, join spec.Join, fg spec.FeatureGroup, fgf *fgFeatures, pks []*feature,
	loggingMetaData, featureVectorWithInferenceHelpers bool) []*feature {
	var selected []*feature
	if inferenceHelperColumns {
		for _, tdf := range join.Features {
			if !tdf.InferenceHelper {
				continue
			}
			f := fgf.get(tdf.Name)
			if f == nil || !f.OfflineOnly {
				selected = append(selected, f)
			}
		}
	} else {
		for _, tdf := range sortedByIndex(join.Features) {
			if tdf.Label || tdf.TrainingHelper {
				continue
			}
			if !(loggingMetaData || featureVectorWithInferenceHelpers || !tdf.InferenceHelper) {
				continue
			}
			f := fgf.get(tdf.Name)
			if f == nil || !f.OfflineOnly {
				selected = append(selected, f)
			}
		}
	}
	if batch {
		for _, pk := range pks {
			if !containsFeature(selected, pk) {
				selected = append(selected, pk)
			}
		}
	}
	// join.getLeftFeatureGroup() == null holds for the root join only.
	if loggingMetaData && !join.LeftFGSet && fg.EventTime != "" {
		selected = append(selected, fgf.get(fg.EventTime))
	}
	return selected
}

func sortedByIndex(fs []spec.TDFeature) []spec.TDFeature {
	out := append([]spec.TDFeature(nil), fs...)
	for i := 1; i < len(out); i++ {
		for j := i; j > 0 && out[j].Index < out[j-1].Index; j-- {
			out[j], out[j-1] = out[j-1], out[j]
		}
	}
	return out
}

// getTrainingDatasetFeatures :1305-1323.
func getTrainingDatasetFeatures(inferenceHelperColumns, featureVectorWithInferenceHelpers bool, join spec.Join) []spec.TDFeature {
	var out []spec.TDFeature
	for _, tdf := range sortedByIndex(join.Features) {
		if inferenceHelperColumns {
			if tdf.InferenceHelper {
				out = append(out, tdf)
			}
			continue
		}
		if tdf.Label || tdf.TrainingHelper {
			continue
		}
		if !(featureVectorWithInferenceHelpers || !tdf.InferenceHelper) {
			continue
		}
		out = append(out, tdf)
	}
	return out
}

// collectSourceFeatures :361-379 + resolveCollectSources / parseStructFieldNames.
func collectSourceFeatures(join spec.Join, fg spec.FeatureGroup, fgf *fgFeatures, pks []*feature) []*feature {
	sources := append([]*feature(nil), pks...)
	for _, tdf := range join.Features {
		names := resolveCollectSources(join, fg, tdf)
		if names == nil {
			continue
		}
		for _, name := range names {
			if src := fgf.get(name); src != nil && !containsFeature(sources, src) {
				sources = append(sources, src)
			}
		}
	}
	return sources
}

// resolveCollectSources: the field names of the persisted
// array<struct<...>> type of the join's synthesized collect feature.
func resolveCollectSources(join spec.Join, fg spec.FeatureGroup, tdf spec.TDFeature) []string {
	if join.CollectN == nil || tdf.Type == nil || tdf.Name != CollectFeatureName(fg) {
		return nil
	}
	return ParseStructFieldNames(*tdf.Type)
}

// CollectFeatureName is ConstructorController.collectFeatureName.
func CollectFeatureName(fg spec.FeatureGroup) string { return fg.Name + "_collect" }

// ParseStructFieldNames parses the field names of array<struct<a:int,b:decimal(10,2)>>.
func ParseStructFieldNames(t string) []string {
	names := []string{}
	if !strings.HasPrefix(t, "array<struct<") || !strings.HasSuffix(t, ">>") {
		return names
	}
	body := t[len("array<struct<") : len(t)-2]
	depth := 0
	var field strings.Builder
	for _, c := range body {
		if c == '<' || c == '(' {
			depth++
		} else if c == '>' || c == ')' {
			depth--
		}
		if c == ',' && depth == 0 {
			names = append(names, structFieldName(field.String()))
			field.Reset()
		} else {
			field.WriteRune(c)
		}
	}
	if field.Len() > 0 {
		names = append(names, structFieldName(field.String()))
	}
	return names
}

func structFieldName(field string) string {
	if i := strings.IndexByte(field, ':'); i >= 0 {
		field = field[:i]
	}
	return strings.TrimSpace(field)
}

// aggregateSourceFeatures :384-402.
func aggregateSourceFeatures(aggSpec spec.AggSpec, fgf *fgFeatures, pks []*feature) []*feature {
	var sources []*feature
	for _, e := range aggSpec {
		if e.Key == "*" {
			if len(pks) > 0 && !containsFeature(sources, pks[0]) {
				sources = append(sources, pks[0])
			}
			continue
		}
		for _, name := range strings.Split(e.Key, ",") {
			if src := fgf.get(name); src != nil && !containsFeature(sources, src) {
				sources = append(sources, src)
			}
		}
	}
	return sources
}

// aggregateOutputs :442-472.
func aggregateOutputs(aggSpec spec.AggSpec, aliasPrefix string) string {
	var out strings.Builder
	for _, e := range aggSpec {
		for _, fn := range e.Fns {
			if out.Len() > 0 {
				out.WriteString(", ")
			}
			switch {
			case e.Key == "*":
				out.WriteString("COUNT(*) AS `" + aliasPrefix + "count`")
			case strings.Contains(e.Key, ","):
				var args strings.Builder
				for _, name := range strings.Split(e.Key, ",") {
					if args.Len() > 0 {
						args.WriteString(", ")
					}
					args.WriteString("`" + name + "`")
				}
				out.WriteString("MAX(" + strings.ToUpper(fn) + "(" + args.String() + ")) AS `" + aliasPrefix +
					strings.ReplaceAll(e.Key, ",", "_") + "_" + strings.ToLower(fn) + "`")
			default:
				out.WriteString(strings.ToUpper(fn) + "(`" + e.Key + "`) AS `" + aliasPrefix + e.Key + "_" + strings.ToLower(fn) + "`")
			}
		}
	}
	return out.String()
}

// aggregateOutputFeatureNames :610-627.
func aggregateOutputFeatureNames(aggSpec spec.AggSpec, aliasPrefix string) []string {
	var names []string
	for _, e := range aggSpec {
		for _, fn := range e.Fns {
			switch {
			case e.Key == "*":
				names = append(names, aliasPrefix+"count")
			case strings.Contains(e.Key, ","):
				names = append(names, aliasPrefix+strings.ReplaceAll(e.Key, ",", "_")+"_"+strings.ToLower(fn))
			default:
				names = append(names, aliasPrefix+e.Key+"_"+strings.ToLower(fn))
			}
		}
	}
	return names
}

// applyRonsqlAggregate :484-520.
func applyRonsqlAggregate(dto *Statement, join spec.Join, fg spec.FeatureGroup, q *query, entityKeys []*feature, batch bool, extraWhere string) error {
	if join.Aggregate == nil {
		return nil
	}
	if batch && len(entityKeys) != 1 {
		return nil
	}
	if len(entityKeys) == 0 {
		return fmt.Errorf("INTERNAL: aggregate statement without an entity key (Java throws IndexOutOfBoundsException)")
	}
	outputs := aggregateOutputs(join.Aggregate, "")
	var where strings.Builder
	if batch {
		where.WriteString("`" + entityKeys[0].Name + "` IN (?)")
	} else {
		for _, k := range entityKeys {
			if where.Len() > 0 {
				where.WriteString(" AND ")
			}
			where.WriteString("`" + k.Name + "` = ?")
		}
	}
	where.WriteString(extraWhere)
	if join.Window != nil && fg.EventTime != "" {
		where.WriteString(" AND `" + fg.EventTime + "` >= ?")
	}
	keyCol := entityKeys[0].Name
	sel := outputs
	groupBy := ""
	if batch {
		sel = "`" + keyCol + "`, " + outputs
		groupBy = " GROUP BY `" + keyCol + "`"
	}
	dto.QueryRonsql = strp("SELECT " + sel + " FROM `" + q.table() + "` WHERE " + where.String() + groupBy + ";")
	dto.RonsqlDatabase = strp(q.project)
	dto.AggregateWindow = join.Window
	return nil
}

// applyMysqlAggregate :531-580.
func applyMysqlAggregate(dto *Statement, join spec.Join, fg spec.FeatureGroup, q *query, entityKeys []*feature, batch bool, extraWhere string) {
	if join.Aggregate == nil {
		return
	}
	aliasPrefix := ""
	if dto.Prefix != nil {
		aliasPrefix = *dto.Prefix
	}
	outputs := aggregateOutputs(join.Aggregate, aliasPrefix)
	var keySelect, keySelectAliased strings.Builder
	for _, k := range entityKeys {
		if keySelect.Len() > 0 {
			keySelect.WriteString(", ")
			keySelectAliased.WriteString(", ")
		}
		keySelect.WriteString("`" + k.Name + "`")
		keySelectAliased.WriteString("`" + k.Name + "`")
		if aliasPrefix != "" {
			keySelectAliased.WriteString(" AS `" + aliasPrefix + k.Name + "`")
		}
	}
	var where strings.Builder
	if batch {
		if len(entityKeys) == 1 {
			where.WriteString(keySelect.String())
		} else {
			where.WriteString("(" + keySelect.String() + ")")
		}
		where.WriteString(" IN (?)")
	} else {
		for _, k := range entityKeys {
			if where.Len() > 0 {
				where.WriteString(" AND ")
			}
			where.WriteString("`" + k.Name + "` = ?")
		}
	}
	where.WriteString(extraWhere)
	if join.Window != nil && fg.EventTime != "" {
		where.WriteString(" AND `" + fg.EventTime + "` >= ?")
		dto.AggregateWindow = join.Window
	}
	sel := outputs
	groupBy := ""
	if batch {
		sel = keySelectAliased.String() + ", " + outputs
		groupBy = " GROUP BY " + keySelect.String()
	}
	dto.QueryOnline = strp("SELECT " + sel + " FROM `" + q.project + "`.`" + q.table() + "` WHERE " + where.String() + groupBy)
	dto.AggregateFeatureNames = aggregateOutputFeatureNames(join.Aggregate, aliasPrefix)
}

// buildDTO :629-701 (the Calcite rendering goes through mysqltwin).
func (b *builder) buildDTO(q *query, bindKeys []*feature, fgID, statementIndex int, batch bool, prefix *string,
	collectN *int, collectOrderBy *feature, collectAscending bool, extraFilters []filterLeaf, ronsqlExtraWhere string) (Statement, error) {
	if len(bindKeys) == 0 {
		return Statement{}, fmt.Errorf("INTERNAL: statement without bind keys (Java throws IndexOutOfBoundsException)")
	}
	params := make([]Param, 0, len(bindKeys))
	for i, k := range bindKeys {
		params = append(params, Param{Name: k.Name, Index: i + 1})
	}
	var cs []mysqltwin.Col
	for _, f := range q.features {
		if f == nil {
			return Statement{}, fmt.Errorf("INTERNAL: selected feature is not a column of %s (Java: NullPointerException in Calcite)", q.table())
		}
		a := f.Alias
		if a == "" {
			a = alias
		}
		out := f.Name
		if f.Prefix != nil {
			out = *f.Prefix + f.Name
		}
		cs = append(cs, mysqltwin.Col{Alias: a, Name: f.Name, Out: out})
	}
	keyNames := make([]string, len(bindKeys))
	for i, k := range bindKeys {
		keyNames[i] = k.Name
	}
	rootAlias := alias
	if q.nested != nil {
		rootAlias = q.nested.root.Alias
	}
	where := mysqltwin.KeyWhere(rootAlias, keyNames, batch)
	for _, lf := range extraFilters {
		where += " AND `" + rootAlias + "`.`" + lf.feature.Name + "` " + mysqltwin.Operator(lf.condition) + " " +
			mysqltwin.Literal(lf.value, lf.feature.Type)
	}
	t := mysqltwin.Table{DB: q.project, Name: q.table(), Alias: alias}
	var sql string
	var scan *string
	if q.nested != nil {
		sql = mysqltwin.Nested(cs, q.nested.root, q.nested.joins, where)
	} else if collectN != nil && collectOrderBy != nil {
		order := mysqltwin.Col{Alias: alias, Name: collectOrderBy.Name}
		if !batch {
			scan = strp(mysqltwin.CollectScan(cs, t, where, order))
		}
		sql = mysqltwin.CollectWindow(cs, t, where, keyNames, order, collectAscending)
	} else {
		sql = mysqltwin.PointRead(cs, t, where)
	}
	dto := Statement{
		FeatureGroupID: fgID, PreparedStatementIndex: statementIndex, PreparedStatementParameters: params,
		QueryOnline: strp(sql), Prefix: prefix,
	}
	if collectOrderBy != nil {
		dto.CollectN = collectN
	}
	if collectN != nil && collectOrderBy != nil {
		dto.CollectFeatureName = strp(CollectFeatureName(q.fg))
		dto.CollectOrderBy = strp(collectOrderBy.Name)
		dto.CollectAscending = boolp(collectAscending)
		dto.CollectFilterApplied = boolp(len(extraFilters) > 0)
		names := make([]string, 0, len(q.features))
		for _, f := range q.features {
			names = append(names, f.Name)
		}
		dto.CollectSourceFeatures = names
		dto.QueryOnlineScan = scan
	}
	if collectN != nil && collectOrderBy != nil && !batch {
		dto.QueryRonsql = strp(buildRonsqlCollectTemplate(q, bindKeys, collectOrderBy, *collectN, ronsqlExtraWhere))
		dto.RonsqlDatabase = strp(q.project)
	}
	return dto, nil
}

// conjunctiveFilterConditions :703-718.  Returns isNil when the tree
// contains an OR (Java returns null).
func conjunctiveFilterConditions(filters []spec.Filter) ([]spec.Filter, bool) {
	if len(filters) == 0 {
		return []spec.Filter{}, false
	}
	var out []spec.Filter
	for _, f := range filters {
		if f.Logic == spec.LogicOr {
			return nil, true
		}
		if f.Feature != "" || f.Condition != nil || f.Value != nil {
			out = append(out, f)
		}
	}
	if out == nil {
		out = []spec.Filter{}
	}
	return out, false
}

// renderRonsqlCondition :723-751.
func renderRonsqlCondition(cond spec.Filter, fgf *fgFeatures) (string, bool) {
	if cond.ValueFeatureGroupID != nil || cond.Value == nil || cond.Condition == nil || !renderableConditions[*cond.Condition] {
		return "", false
	}
	f := fgf.get(cond.Feature)
	if f == nil {
		return "", false
	}
	literal, ok := renderRonsqlLiteral(*cond.Value, f.Type)
	if !ok {
		return "", false
	}
	var op string
	switch *cond.Condition {
	case spec.CondEquals:
		op = "="
	case spec.CondNotEquals:
		op = "<>"
	case spec.CondGreaterThan:
		op = ">"
	case spec.CondGreaterThanOrEqual:
		op = ">="
	case spec.CondLessThan:
		op = "<"
	case spec.CondLessThanOrEqual:
		op = "<="
	case spec.CondLike:
		op = "LIKE"
	default:
		return "", false
	}
	return "`" + cond.Feature + "` " + op + " " + literal, true
}

// renderRonsqlLiteral :754-770.
func renderRonsqlLiteral(value, featureType string) (string, bool) {
	t := strings.ToLower(featureType)
	for _, p := range numericTypePrefixes {
		if strings.HasPrefix(t, p) {
			if numericLiteral.MatchString(value) {
				return value, true
			}
			return "", false
		}
	}
	if strings.HasPrefix(t, "boolean") {
		return "", false
	}
	for i := 0; i < len(value); i++ {
		if value[i] < 0x20 || value[i] == '\\' {
			return "", false
		}
	}
	return "'" + strings.ReplaceAll(value, "'", "''") + "'", true
}

// buildRonsqlCollectTemplate :780-800.
func buildRonsqlCollectTemplate(q *query, entityKeys []*feature, orderBy *feature, n int, extraWhere string) string {
	var cols strings.Builder
	for _, f := range q.features {
		if cols.Len() > 0 {
			cols.WriteString(", ")
		}
		cols.WriteString("`" + f.Name + "`")
	}
	var where strings.Builder
	for _, k := range entityKeys {
		if where.Len() > 0 {
			where.WriteString(" AND ")
		}
		where.WriteString("`" + k.Name + "` = ?")
	}
	return "WITH t AS (SELECT " + cols.String() + " FROM `" + q.table() + "` WHERE " + where.String() + extraWhere +
		" ORDER BY `" + orderBy.Name + "` DESC" + " LIMIT " + fmt.Sprintf("%d", n) + ") SELECT " + cols.String() + " FROM t;"
}

