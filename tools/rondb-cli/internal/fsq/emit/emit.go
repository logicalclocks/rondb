// retrieveRightJoinsLists (NestedTrainingDatasetJoinTree): STAR joins and
// the roots of nested subtrees.
func retrieveRightJoinsLists(joins []spec.Join) (star, nested []spec.Join) {
	parentIndexes := map[int]bool{}
	for _, j := range joins {
		parentIndexes[j.Parent] = true
	}
	for _, j := range joins {
		if j.Index == 0 || (j.Parent == 0 && !parentIndexes[j.Index]) {
			star = append(star, j)
		} else if j.Parent == 0 {
			nested = append(nested, j)
		}
	}
	return star, nested
}

// constructTree (NestedTrainingDatasetJoinTree.constructTreeRecursive): the
// subtree rooted at root in depth-first, list order, recursion limit 20.
func constructTree(root spec.Join, joins []spec.Join) ([]spec.Join, error) {
	var tree []spec.Join
	var rec func(cur spec.Join, limit int) error
	rec = func(cur spec.Join, limit int) error {
		if limit <= 0 {
			return spec.Gate(spec.CodeNestedJoinsRecursionExceeded,
				"current recursion limit exceeded, limit: %d, root training dataset join id: %d", limit, root.Index+1)
		}
		tree = append(tree, cur)
		for _, j := range joins {
			if j.Parent == cur.Index {
				if err := rec(j, limit-1); err != nil {
					return err
				}
			}
		}
		return nil
	}
	if err := rec(root, 20); err != nil {
		return nil, err
	}
	return tree, nil
}

func (b *builder) createSnowflakePreparedStatementDTOS(joins []spec.Join, hasFilters bool) ([]Statement, error) {
	if hasFilters {
		for _, j := range joins {
			if j.CollectN != nil || j.Aggregate != nil {
				return nil, spec.Gate(spec.CodeCollectUnsupportedOnlineFilt,
					"snowflake-schema feature views cannot apply their filters to online collect/aggregation statements")
			}
		}
	}
	star, nested := retrieveRightJoinsLists(joins)
	var out []Statement
	if len(star) > 0 {
		dtos, err := b.createServingPreparedStatementDTOS(star, []spec.Filter{}, false)
		if err != nil {
			return nil, err
		}
		out = dtos
	}
	return b.constructSnowflakeJoinsDTO(joins, nested, out)
}

// validateExtractPrimaryFeatures :1191-1222.
func (b *builder) validateExtractPrimaryFeatures(join spec.Join) ([]*feature, error) {
	fg := b.fgs[join.FG]
	if !fg.OnlineEnabled() {
		return nil, notOnlineEnabled(fg)
	}
	fgf := b.featuresOf(fg, join.Prefix)
	pks := primaryKeys(fgf)
	if len(pks) == 0 {
		return nil, primaryKeyRequired()
	}
	return pks, nil
}

func (b *builder) constructSnowflakeJoinsDTO(joins []spec.Join, roots []spec.Join, out []Statement) ([]Statement, error) {
	for _, root := range roots {
		childJoins, err := constructTree(root, joins)
		if err != nil {
			return nil, err
		}
		for _, cj := range childJoins {
			if cj.Index == root.Index {
				continue
			}
			if _, err := b.validateExtractPrimaryFeatures(cj); err != nil {
				return nil, err
			}
		}
		rootPKs, err := b.validateExtractPrimaryFeatures(root)
		if err != nil {
			return nil, err
		}
		// nestedLeftQuery = trainingDatasetController.getQuery(childJoins, nestedFeatures, ...)
		q, err := b.nestedQueryOf(root, childJoins, rootPKs)
		if err != nil {
			return nil, err
		}
		fgFeaturesByID := map[int][]spec.Feature{}
		for _, cj := range childJoins {
			if _, ok := fgFeaturesByID[cj.FG]; !ok {
				fgFeaturesByID[cj.FG] = b.fgs[cj.FG].Features
			}
		}
		templates := b.buildRonsqlSnowflakeTemplates(root, childJoins, rootPKs, fgFeaturesByID)
		dto, err := b.buildDTO(q, rootPKs, b.fgs[root.FG].ID, root.Index, b.opt.Batch, root.Prefix, nil, nil, false, nil, "")
		if err != nil {
			return nil, err
		}
		dto.SnowflakeTemplate = boolp(true)
		if templates != nil {
			dto.SnowflakeTemplates = templates
			dto.RonsqlDatabase = strp(q.project)
		}
		out = append(out, dto)
	}
	return out, nil
}

// nestedQueryOf mirrors what TrainingDatasetController.getQuery produces for
// a snowflake subtree and the join validation it performs on the way
// (QueryController.checkFeatureExistsAndSetAttributes / checkJoinOnIsPrimaryKey).
func (b *builder) nestedQueryOf(root spec.Join, childJoins []spec.Join, rootPKs []*feature) (*query, error) {
	rootFG := b.fgs[root.FG]
	aliasOf := map[int]string{}
	for i, cj := range childJoins {
		aliasOf[cj.Index] = fmt.Sprintf("fg%d", i)
	}
	var features []*feature
	addFeatures := func(cj spec.Join) {
		fg := b.fgs[cj.FG]
		fgf := b.featuresOf(fg, cj.Prefix)
		for _, tdf := range getTrainingDatasetFeatures(b.opt.InferenceHelpers, b.opt.Logging || b.opt.VectorWithHelpers, cj) {
			f := fgf.get(tdf.Name)
			if f != nil {
				cp := *f
				cp.Alias = aliasOf[cj.Index]
				features = append(features, &cp)
			} else {
				features = append(features, nil)
			}
		}
	}
	for _, cj := range childJoins {
		if cj.Index == root.Index {
			continue
		}
		addFeatures(cj)
	}
	addFeatures(root)
	if b.opt.Batch {
		for _, pk := range rootPKs {
			cp := *pk
			cp.Alias = aliasOf[root.Index]
			features = append(features, &cp)
		}
	}
	nq := &nestedQuery{root: mysqltwin.Table{DB: rootFG.OnlineDatabase(), Name: rootFG.TableName(), Alias: aliasOf[root.Index]}}
	for _, cj := range childJoins {
		if cj.Index == root.Index {
			continue
		}
		parent := childJoinByIndex(childJoins, cj.Parent)
		parentFG := b.fgs[parent.FG]
		childFG := b.fgs[cj.FG]
		var on [][2]string
		for _, c := range cj.On {
			if _, ok := parentFG.Feature(c[0]); !ok {
				return nil, spec.Gate(spec.CodeFeatureDoesNotExist, "Could not find Join feature %s in feature group: %s", c[0], parentFG.Name)
			}
			if _, ok := childFG.Feature(c[1]); !ok {
				return nil, spec.Gate(spec.CodeFeatureDoesNotExist, "Could not find Join feature %s in feature group: %s", c[1], childFG.Name)
			}
			on = append(on, [2]string{c[0], c[1]})
		}
		if err := checkJoinOnIsPrimaryKey(childFG, cj.On); err != nil {
			return nil, err
		}
		nq.joins = append(nq.joins, mysqltwin.JoinClause{Type: cj.Type,
			Table:  mysqltwin.Table{DB: childFG.OnlineDatabase(), Name: childFG.TableName(), Alias: aliasOf[cj.Index]},
			Parent: aliasOf[parent.Index], On: on})
	}
	return &query{project: rootFG.OnlineDatabase(), fg: rootFG, features: features, nested: nq}, nil
}

func childJoinByIndex(joins []spec.Join, index int) spec.Join {
	for _, j := range joins {
		if j.Index == index {
			return j
		}
	}
	return spec.Join{}
}

// checkJoinOnIsPrimaryKey (QueryController): the right-hand join columns
// must be exactly the child's primary key.
func checkJoinOnIsPrimaryKey(child spec.FeatureGroup, on [][2]string) error {
	joinOn := map[string]bool{}
	for _, c := range on {
		joinOn[c[1]] = true
	}
	pk := map[string]bool{}
	for _, f := range child.Features {
		if f.Primary {
			pk[f.Name] = true
		}
	}
	for _, c := range on {
		if !pk[c[1]] {
			return spec.Gate(spec.CodeForeignKeyNotPrimaryKey, "%s is not primary key in feature group: %s", c[1], child.Name)
		}
	}
	for _, f := range child.Features {
		if f.Primary && !joinOn[f.Name] {
			return spec.Gate(spec.CodeJoinOnPartialPrimaryKey,
				"%s is not included in the list of keys to make the join on, but is a part of primary key of feature group: %s", f.Name, child.Name)
		}
	}
	return nil
}

// buildRonsqlSnowflakeTemplates :966-1062.
func (b *builder) buildRonsqlSnowflakeTemplates(root spec.Join, childJoins []spec.Join, rootPKs []*feature, fgFeaturesByID map[int][]spec.Feature) []string {
	if b.opt.Batch && len(rootPKs) != 1 {
		return nil
	}
	var nested []spec.Join
	for _, cj := range childJoins {
		if cj.Index != root.Index {
			nested = append(nested, cj)
		}
	}
	if len(nested) == 0 {
		return nil
	}
	allInner, allLeft := true, true
	rootFS := b.fgs[root.FG].FeaturestoreID
	for _, cj := range nested {
		if cj.Type != spec.JoinInner && cj.Type != spec.JoinLeft {
			return nil
		}
		if cj.Type != spec.JoinInner {
			allInner = false
		}
		if cj.Type != spec.JoinLeft {
			allLeft = false
		}
		if b.fgs[cj.FG].FeaturestoreID != rootFS {
			return nil
		}
		if len(cj.On) == 0 {
			return nil
		}
		childPKs := map[string]bool{}
		for _, f := range fgFeaturesByID[cj.FG] {
			if f.Primary {
				childPKs[f.Name] = true
			}
		}
		right := map[string]bool{}
		for _, c := range cj.On {
			right[c[1]] = true
		}
		if len(right) != len(childPKs) {
			return nil
		}
		for k := range right {
			if !childPKs[k] {
				return nil
			}
		}
	}
	byIndex := map[int]spec.Join{}
	for _, cj := range nested {
		byIndex[cj.Index] = cj
	}
	if allInner {
		t := b.buildSnowflakeStatement(root, nested, nested, rootPKs, fgFeaturesByID)
		if t == nil {
			return nil
		}
		return []string{*t}
	}
	if !allLeft {
		return nil
	}
	var templates []string
	for _, target := range nested {
		var chain []spec.Join
		cursor, ok := target, true
		for ok && cursor.Parent != root.Index {
			chain = append([]spec.Join{cursor}, chain...)
			cursor, ok = byIndex[cursor.Parent]
		}
		if !ok {
			return nil
		}
		chain = append([]spec.Join{cursor}, chain...)
		t := b.buildSnowflakeStatement(root, chain, []spec.Join{target}, rootPKs, fgFeaturesByID)
		if t == nil {
			continue
		}
		templates = append(templates, *t)
	}
	if len(templates) == 0 {
		return nil
	}
	return templates
}

// buildSnowflakeStatement :1067-1180.
func (b *builder) buildSnowflakeStatement(root spec.Join, traversed, projection []spec.Join, rootPKs []*feature, fgFeaturesByID map[int][]spec.Feature) *string {
	var cteColumns []string
	seen := map[string]bool{}
	addCol := func(c string) {
		if !seen[c] {
			seen[c] = true
			cteColumns = append(cteColumns, c)
		}
	}
	if b.opt.Batch {
		for _, pk := range rootPKs {
			addCol(pk.Name)
		}
	}
	var joinClauses strings.Builder
	for _, cj := range traversed {
		parentIsRoot := cj.Parent == root.Index
		parentAlias := "b"
		if !parentIsRoot {
			parentAlias = fmt.Sprintf("j%d", cj.Parent)
		}
		childAlias := fmt.Sprintf("j%d", cj.Index)
		var on strings.Builder
		for _, c := range cj.On {
			if parentIsRoot {
				addCol(c[0])
			}
			if on.Len() > 0 {
				on.WriteString(" AND ")
			}
			on.WriteString("`" + childAlias + "`.`" + c[1] + "` = `" + parentAlias + "`.`" + c[0] + "`")
		}
		joinClauses.WriteString(" JOIN `" + b.fgs[cj.FG].TableName() + "` AS `" + childAlias + "` ON " + on.String())
	}
	var projections strings.Builder
	for _, cj := range projection {
		childAlias := fmt.Sprintf("j%d", cj.Index)
		prefix := cj.PrefixOrEmpty()
		for _, tdf := range getTrainingDatasetFeatures(b.opt.InferenceHelpers, b.opt.Logging || b.opt.VectorWithHelpers, cj) {
			if projections.Len() > 0 {
				projections.WriteString(", ")
			}
			projections.WriteString("`" + childAlias + "`.`" + tdf.Name + "` AS `" + prefix + tdf.Name + "`")
		}
	}
	if projections.Len() == 0 {
		return nil
	}
	rootColumns := map[string]bool{}
	for _, f := range fgFeaturesByID[root.FG] {
		rootColumns[f.Name] = true
	}
	for _, c := range cteColumns {
		if !rootColumns[c] {
			return nil
		}
	}
	var cteSelect strings.Builder
	for _, c := range cteColumns {
		cteSelect.WriteString("`" + c + "`, ")
	}
	var where strings.Builder
	if b.opt.Batch {
		where.WriteString("`" + rootPKs[0].Name + "` IN (?)")
	} else {
		for _, pk := range rootPKs {
			if where.Len() > 0 {
				where.WriteString(" AND ")
			}
			where.WriteString("`" + pk.Name + "` = ?")
		}
	}
	groupBy := ""
	for i, c := range cteColumns {
		if i > 0 {
			groupBy += ", "
		}
		groupBy += "`" + c + "`"
	}
	if b.opt.Batch {
		for _, pk := range rootPKs {
			projections.WriteString(", `b`.`" + pk.Name + "` AS `" + pk.Name + "`")
		}
	}
	s := "WITH `b` AS (SELECT " + cteSelect.String() + "COUNT(*) AS `hw_cnt` FROM `" + b.fgs[root.FG].TableName() +
		"` WHERE " + where.String() + " GROUP BY " + groupBy + ") SELECT " + projections.String() + " FROM `b`" +
		joinClauses.String() + ";"
	return &s
}
