// Build ports getServingStatements for a feature view (or a query-backed
// training dataset) and returns the ordered ServingPreparedStatementDTO
// list.  Hopsworks exceptions come back as *spec.GateError.
func Build(v *spec.View) ([]Statement, error) {
	if err := v.Normalize(); err != nil {
		return nil, err
	}
	b := &builder{v: v, fgs: v.FGMap(), opt: v.Options}
	if v.TrainingDataset {
		// build(uriInfo, resourceRequest, project, featurestore, id, batch):
		// no helper options on the training-dataset entry point.
		b.opt = spec.Options{Batch: v.Options.Batch}
	}
	joins := v.JoinsSorted()
	for _, j := range joins {
		if _, ok := b.fgs[j.FG]; !ok {
			return nil, spec.Gate(spec.CodeQueryFailedFGDeleted, "")
		}
	}
	snowflake := false
	for _, j := range joins {
		if j.Parent != 0 {
			snowflake = true
		}
	}
	if snowflake {
		return b.createSnowflakePreparedStatementDTOS(joins, len(v.Filters) > 0)
	}
	conds, isNil := conjunctiveFilterConditions(v.Filters)
	return b.createServingPreparedStatementDTOS(joins, conds, isNil)
}

// featuresOf builds the join's LinkedHashMap<String, Feature>.
func (b *builder) featuresOf(fg spec.FeatureGroup, prefix *string) *fgFeatures {
	m := &fgFeatures{byName: map[string]*feature{}}
	for _, c := range fg.Features {
		if _, dup := m.byName[c.Name]; dup {
			continue // toMap merge (a, b) -> a keeps the first
		}
		f := &feature{Name: c.Name, Type: c.Type, Primary: c.Primary, DefaultValue: c.DefaultValue,
			OfflineOnly: c.OfflineOnly, Prefix: prefix, FGID: fg.ID, Alias: alias}
		m.list = append(m.list, f)
		m.byName[c.Name] = f
	}
	return m
}

func primaryKeys(m *fgFeatures) []*feature {
	var pks []*feature
	for _, f := range m.list {
		if f.Primary {
			pks = append(pks, f)
		}
	}
	return pks
}

func containsFeature(list []*feature, f *feature) bool {
	for _, x := range list {
		if x != nil && f != nil && x.Name == f.Name && x.FGID == f.FGID {
			return true
		}
	}
	return false
}

func notOnlineEnabled(fg spec.FeatureGroup) error {
	return spec.Gate(spec.CodeFeaturestoreOnlineNotEnabled,
		"Inference vector is only available for training datasets generated by online enabled feature groups. Feature group `%s` is not online enabled.", fg.Name)
}

func primaryKeyRequired() error {
	return spec.Gate(spec.CodePrimaryKeyRequired,
		"Inference vector is only available for training datasets generated by feature groups with at least 1 primary key")
}

