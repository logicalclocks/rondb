// HazardCases renders the hazards as envelope cases of a run.
func HazardCases(seed uint64) []EnvCase {
	out := make([]EnvCase, 0, len(Hazards))
	for i, h := range Hazards {
		out = append(out, EnvCase{ID: EnvVersion + "-hazard-" + h.ID, Seed: seed, Index: -1 - i, Production: "hazard",
			SQL: h.SQL, Ordered: h.Ordered, Constructs: []string{"hazard-" + h.ID}, Signature: "hazard|" + h.ID, Hazard: h.ID})
	}
	return out
}
