package fuzz

// Hazards (random_generator.md §5.4): shapes with a recorded HANG or CRASH
// in mysql-test/suite/ronsql_cte/findings/_discovery_log.md, translated
// from the TPC-H schema to the feature-store schema.  They are never
// generated by default; `.fs_fuzz envelope --include-hazards` runs them
// single-threaded with a short timeout and a crash probe after each.

// Hazard is one discovery-log row translated to the feature-store schema.
type Hazard struct {
	ID      string // discovery-log id, e.g. "D18"
	Class   string // HANG | CRASH | ERROR
	Summary string
	SQL     string
	Ordered bool
}

